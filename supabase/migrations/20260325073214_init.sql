--
-- Name: gatherings_with_guests; Type: MATERIALIZED VIEW; Schema: public; Owner: postgres
--

CREATE MATERIALIZED VIEW public.gatherings_with_guests AS
 SELECT g.id,
    g.created_at,
    g.owner_id,
    g.start_date,
    g.comment_owner,
    g.guests_max,
    g.comment_club,
    g.club_id,
    g.table_id,
    g.own_name,
    g.gamebox_id,
    gg.user_id,
    gg.guests_number,
    rd.raw_user_meta_data,
    p.telegram_username,
    p.full_name,
    p.avatar_url,
    json_build_object('id', gb.id, 'title', gb.title, 'photo_url', gb.photo_url, 'id_tesera', gb.id_tesera, 'id_bgg', gb.id_bgg, 'rating_tesera', gb.rating_tesera, 'rating_bgg', gb.rating_bgg, 'link_tesera', gb.link_tesera, 'link_bgg', gb.link_bgg, 'year', gb.year, 'players_min', gb.players_min, 'players_max', gb.players_max, 'players_good', gb.players_good, 'playtime_min', gb.playtime_min, 'playtime_max', gb.playtime_max, 'playtime_avg', gb.playtime_avg, 'alias_tesera', gb.alias_tesera, 'titles', gb.titles) AS gamebox,
    json_build_object('id', owner.id, 'metadata', owner.raw_user_meta_data) AS owneruser
   FROM (((((public.gatherings g
     LEFT JOIN ( SELECT gatherings_guests.gathering_id,
            gatherings_guests.user_id,
            gatherings_guests.guests_number
           FROM public.gatherings_guests
          WHERE (gatherings_guests.guests_number > 0)) gg ON ((g.id = gg.gathering_id)))
     LEFT JOIN public.profiles p ON ((gg.user_id = p.id)))
     LEFT JOIN public.users_raw_data owner ON ((g.owner_id = owner.id)))
     LEFT JOIN public.users_raw_data rd ON ((gg.user_id = rd.id)))
     LEFT JOIN public.gameboxes gb ON ((g.gamebox_id = gb.id)))
  WHERE (g.start_date >= (CURRENT_DATE - '1 day'::interval))
  WITH NO DATA;


ALTER TABLE public.gatherings_with_guests OWNER TO postgres;

